package com.tailcat.vpn.core.geo

import java.io.BufferedReader
import java.io.IOException
import java.io.InputStream
import java.io.InputStreamReader
import java.text.Collator
import java.util.Locale

/** One country the user can choose to block. */
data class CountryInfo(
    /** ISO 3166-1 alpha-2 code, upper case. */
    val code: String,
    val name: String,
    /** How many CIDR blocks the bundled data lists for the country. */
    val prefixCount: Int
) {
    /** Regional-indicator flag emoji; devices without the glyphs show the two letters. */
    val flag: String
        get() = String(Character.toChars(REGIONAL_INDICATOR_A + (code[0] - 'A'))) +
            String(Character.toChars(REGIONAL_INDICATOR_A + (code[1] - 'A')))

    private companion object {
        const val REGIONAL_INDICATOR_A = 0x1F1E6
    }
}

/** The bundled country data is missing, unreadable or malformed. */
class CountryRangesException(message: String, cause: Throwable? = null) : IOException(message, cause)

/**
 * The bundled country-to-IP-range data (assets/country_ranges.txt, generated by
 * scripts/geoip/generate_country_ranges.py from the Regional Internet
 * Registries' delegated statistics).
 *
 * Format: `#` comment lines, then one line per country: an upper-case ISO code,
 * a space, and space-separated CIDR prefixes. This class only splits the lines;
 * the native engine validates every prefix it is handed, so a corrupt asset can
 * never reach the data path.
 *
 * The data is offline and read-only: nothing here, or anywhere in the app,
 * looks a destination up online. Registries record where a range was first
 * allocated, not where it is used, so treat the result as best effort.
 */
class CountryRanges(private val open: () -> InputStream) {

    /**
     * Countries present in the data, sorted by their name in [locale]. Codes
     * that are not ISO 3166-1 countries (the registries also use a few
     * regional codes) are left out: they are not something a user can pick.
     */
    fun countries(locale: Locale = Locale.getDefault()): List<CountryInfo> {
        val iso = Locale.getISOCountries().toSet()
        val found = ArrayList<CountryInfo>()
        forEachCountryLine { code, line ->
            if (code in iso && line.length > CODE_LENGTH + 1) {
                val name = Locale.Builder().setRegion(code).build()
                    .getDisplayCountry(locale)
                    .ifBlank { code }
                found += CountryInfo(code, name, line.count { it == ' ' })
            }
        }
        val collator = Collator.getInstance(locale)
        return found.sortedWith { a, b -> collator.compare(a.name, b.name) }
    }

    /**
     * The prefixes of every country in [codes], space-separated, for the
     * native engine. Codes with no data contribute nothing. With nothing
     * selected this returns "" without touching the data, so a missing asset
     * can only matter once the user has actually chosen a country.
     *
     * @throws CountryRangesException when the data cannot be read or is malformed.
     */
    fun prefixesFor(codes: Set<String>): String {
        if (codes.isEmpty()) return ""
        val out = StringBuilder()
        forEachCountryLine { code, line ->
            if (code in codes && line.length > CODE_LENGTH + 1) {
                if (out.isNotEmpty()) out.append(' ')
                out.append(line, CODE_LENGTH + 1, line.length)
            }
        }
        return out.toString()
    }

    private inline fun forEachCountryLine(block: (code: String, line: String) -> Unit) {
        try {
            open().use { stream ->
                BufferedReader(InputStreamReader(stream, Charsets.US_ASCII)).use { reader ->
                    var number = 0
                    while (true) {
                        val line = reader.readLine() ?: break
                        number++
                        if (line.isEmpty() || line[0] == '#') continue
                        if (!isCodeLine(line)) {
                            throw CountryRangesException("Country data line $number is malformed")
                        }
                        block(line.substring(0, CODE_LENGTH), line)
                    }
                }
            }
        } catch (e: CountryRangesException) {
            throw e
        } catch (e: IOException) {
            throw CountryRangesException("Country data could not be read", e)
        }
    }

    private fun isCodeLine(line: String): Boolean =
        line.length >= CODE_LENGTH &&
            line[0] in 'A'..'Z' && line[1] in 'A'..'Z' &&
            (line.length == CODE_LENGTH || line[CODE_LENGTH] == ' ')

    companion object {
        const val ASSET_NAME = "country_ranges.txt"
        private const val CODE_LENGTH = 2
    }
}
