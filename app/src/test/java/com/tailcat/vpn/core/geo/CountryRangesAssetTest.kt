package com.tailcat.vpn.core.geo

import java.math.BigInteger
import java.net.InetAddress
import java.util.Locale
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Checks the exact file the app ships (assets/country_ranges.txt, regenerated
 * by scripts/geoip/generate_country_ranges.py). The native engine validates the
 * same rules at runtime, so a refresh that breaks them fails here, in CI,
 * before it can fail a user's Connect.
 */
class CountryRangesAssetTest {

    private fun asset(): CountryRanges = CountryRanges {
        checkNotNull(javaClass.classLoader?.getResourceAsStream(CountryRanges.ASSET_NAME)) {
            "${CountryRanges.ASSET_NAME} was not found on the test classpath"
        }
    }

    private fun assetLines(): List<String> =
        checkNotNull(javaClass.classLoader?.getResourceAsStream(CountryRanges.ASSET_NAME))
            .bufferedReader(Charsets.US_ASCII).use { it.readLines() }

    @Test
    fun hasTheDocumentedHeader() {
        val lines = assetLines()
        assertEquals("# OpenTailcat country ranges, format 1", lines.first())
        assertTrue(lines.any { it.startsWith("# source: apnic ") })
        assertTrue(lines.any { it.startsWith("# Generated by scripts/geoip/generate_country_ranges.py") })
    }

    @Test
    fun coversTheWorldAndTheCountriesThisFeatureWasBuiltFor() {
        val countries = asset().countries(Locale.ENGLISH)
        val codes = countries.map { it.code }.toSet()
        assertTrue("expected ~240 countries, got ${codes.size}", codes.size > 200)
        for (code in listOf("CN", "KP", "US", "RU", "IR", "DE", "BR")) {
            assertTrue("$code is missing from the data", code in codes)
        }
        assertTrue("China has thousands of ranges", countries.first { it.code == "CN" }.prefixCount > 5000)
        // North Korea has exactly one registry delegation; if this changes, the
        // UI copy and docs that mention it need a second look.
        assertEquals("175.45.176.0/22", asset().prefixesFor(setOf("KP")))
        assertNotNull(countries.firstOrNull { it.code == "CN" && it.name == "China" })
    }

    @Test
    fun countryLinesAreSortedAndUnique() {
        val codes = assetLines().filterNot { it.startsWith("#") || it.isBlank() }.map { it.substring(0, 2) }
        assertEquals("one line per country, sorted by code", codes.sorted().distinct(), codes)
    }

    @Test
    fun everyPrefixIsACanonicalCidrWithinTheEnginesBounds() {
        var checked = 0
        for ((index, line) in assetLines().withIndex()) {
            if (line.startsWith("#") || line.isBlank()) continue
            for (token in line.substring(3).split(' ')) {
                checkPrefix(token, "line ${index + 1}")
                checked++
            }
        }
        assertTrue("expected a world of prefixes, checked $checked", checked > 200_000)
    }

    /** Mirrors core-engine/country_block.go: canonical, no IPv4-mapped form, /4+ and /8+. */
    private fun checkPrefix(token: String, where: String) {
        val slash = token.indexOf('/')
        assertTrue("$where: $token has no prefix length", slash > 0)
        val address = token.substring(0, slash)
        val bits = token.substring(slash + 1).toInt()
        val v6 = ':' in address
        // Numeric literals only, so InetAddress can never reach for DNS.
        if (v6) {
            assertTrue("$where: $token is not a plain IPv6 literal", address.all { it in "0123456789abcdef:" })
        } else {
            assertTrue("$where: $token is not a dotted IPv4 literal", address.all { it in "0123456789." })
        }
        val bytes = InetAddress.getByName(address).address
        assertEquals("$where: $token changed family when parsed", if (v6) 16 else 4, bytes.size)
        val max = bytes.size * 8
        val min = if (v6) 8 else 4
        assertTrue("$where: $token must be /$min../$max", bits in min..max)
        val hostMask = BigInteger.ONE.shiftLeft(max - bits).subtract(BigInteger.ONE)
        assertEquals("$where: $token has host bits set", BigInteger.ZERO, BigInteger(1, bytes).and(hostMask))
        assertFalse("$where: $token is IPv4-mapped", v6 && address.startsWith("::ffff:"))
    }
}
